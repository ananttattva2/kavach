import PDFDocument from "pdfkit";
import path from "node:path";
import type { AuditData, AuditSummary } from "./audit-types";
import { auditTabs } from "./audit-types";

const localTime=(value:string)=>new Intl.DateTimeFormat('en-IN',{timeZone:'Asia/Kolkata',dateStyle:'medium',timeStyle:'short'}).format(new Date(value))+' IST';
export async function auditPdf(
  a: AuditData,
  summary: AuditSummary,
  kind: "letter" | "report",
  generatedBy: string,
): Promise<Buffer> {
  const pdf = new PDFDocument({
    font: path.join(process.cwd(), "assets/fonts/NotoSans-Regular.ttf"),
    size: "A4",
    margins: { top: 52, bottom: 60, left: 52, right: 52 },
    bufferPages: true,
    info: {
      Title:
        kind === "letter" ? "Engagement Letter" : "Pre-Audit Validation Report",
      Author: generatedBy,
      Subject: `${a.snapshot.basic["Client legal name"]} / ${a.year} / ${a.id}`,
    },
  });
  const chunks: Buffer[] = [];
  const done = new Promise<Buffer>((resolve, reject) => {
    pdf.on("data", (chunk) => chunks.push(chunk));
    pdf.on("end", () => resolve(Buffer.concat(chunks)));
    pdf.on("error", reject);
  });
  pdf.font(path.join(process.cwd(), "assets/fonts/NotoSans-Regular.ttf"));
  const text = (value: string, size = 10) => {
    pdf
      .fontSize(size)
      .fillColor("#273c35")
      .text(value, { lineGap: 4, paragraphGap: 6 });
  };
  if (kind === "letter") {
    text(a.letter.content.split("\n")[0], 17);
    pdf.moveDown();
    // Saved plain text is used verbatim; PDFKit wraps and paginates long paragraphs.
    text(a.letter.content.split("\n").slice(1).join("\n"), 10.5);
  } else {
    text("PRE-AUDIT VALIDATION REPORT", 18);
    text(
      summary.completed && a.stage !== "pre-audit"
        ? "COMPLETED"
        : "DRAFT / IN PROGRESS",
      11,
    );
    text(
      `Client: ${a.snapshot.basic["Client legal name"]}\nCategory: ${a.snapshot.registrationCategory} / ${a.snapshot.wasteStream}\nFinancial year: ${a.year}\nAudit ID: ${a.id}\nAssigned auditor: ${a.auditor.name || "Unassigned"}\nGenerated by: ${generatedBy}\nGenerated at: ${localTime(new Date().toISOString())}\nRequired checks: ${summary.verified}/${summary.required} verified; ${summary.pending} pending; ${summary.notApplicable} not applicable`,
    );
    for (const [tab, title] of auditTabs.entries()) {
      if (pdf.y > 660) pdf.addPage();
      pdf.moveDown();
      text(`${tab + 1}. ${title} — ${summary.tabs[tab].status}`, 13);
      for (const item of summary.items.filter((i) => i.tab === tab)) {
        text(
          `${item.title}: ${!item.required ? "NOT APPLICABLE" : item.verified ? "VERIFIED" : item.stale ? "RE-VERIFICATION REQUIRED" : "PENDING"}`,
          11,
        );
        if (item.facilityId) text(`Facility ID: ${item.facilityId}`);
        for (const [field, value] of Object.entries(item.fields))
          text(`${field}: ${value || "Not provided"}`, 9);
        if (item.naReason) text(`Reason: ${item.naReason}`, 9);
        if (item.missing.length)
          text(`Blocking issues: ${item.missing.join("; ")}`, 9);
        if (item.verified && item.check)
          text(
            `Verified by ${item.check.verifiedBy.name} at ${localTime(item.check.verifiedAt)}`,
            9,
          );
        else if (item.check)
          text(
            `Previous verification is not current: ${item.check.verifiedBy.name}, ${localTime(item.check.verifiedAt)}`,
            9,
          );
        if (item.remark?.text)
          text(
            `Remark: ${item.remark.text}\nBy ${item.remark.by} at ${localTime(item.remark.at)}`,
            9,
          );
        pdf.moveDown(0.5);
      }
    }
    text(
      `Applicability policy: ${a.policy.reason}\nApproved by: ${a.policy.by} at ${localTime(a.policy.at)}`,
      9,
    );
  }
  const range = pdf.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    pdf.switchToPage(i);
    pdf
      .fontSize(8)
      .fillColor("#7b8982")
      .text(
        `${a.year} • ${kind === "letter" ? "Engagement Letter" : "Validation Report"} • ${i + 1} / ${range.count}`,
        52,
        pdf.page.height - 40,
        { lineBreak: false },
      );
  }
  pdf.end();
  return done;
}
